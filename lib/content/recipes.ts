/**
 * Allergens are DERIVED from the ingredient list, including optional ingredients.
 * Optional allergenic ingredients still mark the recipe, because a planner must never
 * silently assume the user will leave something out.
 */
export function deriveRecipeAllergens(recipe: RecipeSeed): string[] {
  const out = new Set<string>();
  for (const ri of recipe.ing) {
    const ing = INGREDIENT_BY_ID.get(ri.id);
    for (const a of ing?.allergens ?? []) out.add(a);
  }
  return [...out].sort();
}

export interface RecipeDietFacts {
  /** No meat or fish. Egg does not make a recipe non-vegetarian here; see containsEgg. */
  vegetarian: boolean;
  vegan: boolean;
  containsEgg: boolean;
  containsMeatOrFish: boolean;
  /** Required ingredients that a vegan would need to omit or replace. */
  nonVeganIngredientIds: string[];
}

/**
 * Diet facts derived from ingredients.
 *
 * `includeOptional: false` (the default) looks only at required ingredients, because an
 * optional spoon of ghee does not stop a roti recipe from being usable by a vegan — the
 * meal planner drops diet-incompatible OPTIONAL ingredients and says so.
 * Allergens are treated differently and always include optional ingredients
 * (see `deriveRecipeAllergens`), because an allergy is a safety constraint.
 */
export function deriveRecipeDietFacts(
  recipe: RecipeSeed,
  { includeOptional = false }: { includeOptional?: boolean } = {},
): RecipeDietFacts {
  let vegetarian = true;
  let vegan = true;
  let containsEgg = false;
  let containsMeatOrFish = false;
  const nonVeganIngredientIds: string[] = [];
  for (const ri of recipe.ing) {
    if (ri.optional && !includeOptional) continue;
    const ing = INGREDIENT_BY_ID.get(ri.id);
    if (!ing) continue;
    if (ing.egg) containsEgg = true;
    if (ing.veg === false && !ing.egg) {
      vegetarian = false;
      containsMeatOrFish = true;
    }
    if (ing.vegan === false) {
      vegan = false;
      nonVeganIngredientIds.push(ri.id);
    }
  }
  return { vegetarian, vegan, containsEgg, containsMeatOrFish, nonVeganIngredientIds };
}

/** Optional ingredients a user on `diet` should omit. Used by the meal planner. */
export function optionalIngredientsToOmit(recipe: RecipeSeed, diet: string): string[] {
  if (diet !== 'vegan' && diet !== 'vegetarian') return [];
  const out: string[] = [];
  for (const ri of recipe.ing) {
    if (!ri.optional) continue;
    const ing = INGREDIENT_BY_ID.get(ri.id);
    if (!ing) continue;
    if (diet === 'vegan' && ing.vegan === false) out.push(ri.id);
    if (diet === 'vegetarian' && ing.veg === false) out.push(ri.id);
  }
  return out;
}

export function validateRecipeCatalog(catalog: RecipeSeed[] = RECIPE_CATALOG): ContentIssue[] {
  const issues: ContentIssue[] = [];
  const ids = new Set<string>();
  for (const r of catalog) {
    if (ids.has(r.id)) issues.push({ kind: 'duplicate_id', id: r.id, detail: 'id appears twice' });
    ids.add(r.id);
    if (r.ing.length === 0) issues.push({ kind: 'no_ingredients', id: r.id, detail: 'empty' });
    if (r.steps.length === 0) issues.push({ kind: 'no_steps', id: r.id, detail: 'empty' });
    if (r.servings < 1) issues.push({ kind: 'bad_servings', id: r.id, detail: String(r.servings) });
    if (!CUISINE_LABELS[r.cuisine]) {
      issues.push({ kind: 'unknown_cuisine', id: r.id, detail: r.cuisine });
    }
    const seen = new Set<string>();
    for (const ri of r.ing) {
      if (!INGREDIENT_BY_ID.has(ri.id)) {
        issues.push({ kind: 'unknown_ingredient', id: r.id, detail: ri.id });
      }
      if (seen.has(ri.id)) {
        issues.push({ kind: 'duplicate_ingredient', id: r.id, detail: ri.id });
      }
      seen.add(ri.id);
      if (ri.qty < 0) issues.push({ kind: 'negative_qty', id: r.id, detail: ri.id });
      const ing = INGREDIENT_BY_ID.get(ri.id);
      if (ing && ri.unit !== ing.unit) {
        issues.push({
          kind: 'unit_mismatch',
          id: r.id,
          detail: `${ri.id}: recipe uses ${ri.unit}, ingredient base unit is ${ing.unit}`,
        });
      }
    }
    for (const a of deriveRecipeAllergens(r)) {
      if (!ALLERGEN_BY_ID.has(a)) issues.push({ kind: 'unknown_allergen', id: r.id, detail: a });
    }
    // Diet tags must agree with the ingredient facts.
    const facts = deriveRecipeDietFacts(r);
    if (r.diet.includes('vegetarian') && !facts.vegetarian) {
      issues.push({ kind: 'diet_conflict', id: r.id, detail: 'tagged vegetarian but has non-veg ingredients' });
    }
    if (r.diet.includes('vegan') && !facts.vegan) {
      issues.push({ kind: 'diet_conflict', id: r.id, detail: 'tagged vegan but has animal ingredients' });
    }
    if (facts.containsEgg && !r.diet.includes('eggetarian') && !r.diet.includes('non_vegetarian')) {
      issues.push({ kind: 'diet_conflict', id: r.id, detail: 'contains egg but not tagged eggetarian' });
    }
    if (facts.containsEgg && r.diet.includes('vegetarian')) {
      issues.push({
        kind: 'diet_conflict',
        id: r.id,
        detail: 'contains egg so it must not be tagged plain vegetarian',
      });
    }
    if (facts.containsMeatOrFish && !r.diet.includes('non_vegetarian')) {
      issues.push({
        kind: 'diet_conflict',
        id: r.id,
        detail: 'meat or fish ingredients but not tagged non_vegetarian',
      });
    }
    if (r.diet.includes('non_vegetarian') && !facts.containsMeatOrFish && !facts.containsEgg) {
      issues.push({
        kind: 'diet_conflict',
        id: r.id,
        detail: 'tagged non_vegetarian but has no animal-flesh ingredients',
      });
    }
  }
  return issues;
}
