import type { Metadata } from 'next';
import Link from 'next/link';
import { redirect } from 'next/navigation';
import { TriangleAlert, Info } from 'lucide-react';
import { requireUser } from '@/lib/auth/session';
import { getActivePlan, getPreference, loadPlanningProfile } from '@/lib/services/plans';
import { activeEquipmentSet } from '@/lib/services/equipment';
import { EXERCISE_BY_ID, EXERCISE_CATALOG } from '@/lib/content/exercises';
import { MOVEMENT_PATTERN_LABELS } from '@/lib/content/exercise-types';
import { isEligible } from '@/lib/engines/workout-generator';
import { buildLimitationFilter } from '@/lib/engines/programming';
import { findSubstitutes } from '@/lib/engines/substitution';
import { Badge, BulletList, Card, CardHeader, Notice, PageHeader } from '@/components/ui';
import { PlanEditor } from '@/components/plan-editor';

export const metadata: Metadata = { title: 'Your plan' };

export default async function PlanPage() {
  const user = await requireUser();
  const plan = getActivePlan(user.id);
  if (!plan) redirect('/workouts');

  const profile = loadPlanningProfile(user.id);
  const equipment = activeEquipmentSet(user.id);
  const lim = buildLimitationFilter(profile.limitations);
  const filters = {
    availableEquipment: equipment.set,
    ageBand: profile.ageBand,
    level: profile.experience,
    excludedExerciseIds: new Set([
      ...lim.excludedExerciseIds,
      ...getPreference<string[]>(user.id, 'disliked_exercises', []),
    ]),
    excludedPatterns: lim.excludedPatterns,
  };

  // Precompute per-exercise swap options on the server so the editor stays light.
  const days = plan.days
    .filter((d) => !d.isRest)
    .map((day) => ({
      id: day.id,
      label: day.label,
      focus: day.focus,
      targetMinutes: day.targetMinutes,
      exercises: day.exercises.map((ex) => {
        const seed = EXERCISE_BY_ID.get(ex.exerciseId);
        const subs = seed
          ? findSubstitutes(seed, filters, { limit: 6 })
          : { options: [], noMatchReason: 'Unknown exercise.' };
        return {
          id: ex.id,
          exerciseId: ex.exerciseId,
          name: ex.name,
          patternLabel: MOVEMENT_PATTERN_LABELS[ex.slotPattern as never] ?? ex.slotPattern,
          role: ex.role,
          sets: ex.sets,
          repsLow: ex.repsLow,
          repsHigh: ex.repsHigh,
          durationSeconds: ex.durationSeconds,
          restSeconds: ex.restSeconds,
          intensityNote: ex.intensityNote,
          rationale: ex.rationale,
          substitutedFrom: ex.substitutedFromExerciseId
            ? (EXERCISE_BY_ID.get(ex.substitutedFromExerciseId)?.name ?? null)
            : null,
          alternatives: subs.options.map((o) => ({
            id: o.exercise.id,
            name: o.exercise.name,
            reason: o.reason,
            samePattern: o.samePattern,
          })),
          noAlternativeReason: subs.options.length === 0 ? (subs.noMatchReason ?? null) : null,
        };
      }),
    }));

  const addableByDay = days.map((day) => {
    const used = new Set(day.exercises.map((e) => e.exerciseId));
    return {
      dayId: day.id,
      options: EXERCISE_CATALOG.filter((ex) => !used.has(ex.id) && isEligible(ex, filters))
        .slice(0, 120)
        .map((ex) => ({ id: ex.id, name: ex.name, pattern: MOVEMENT_PATTERN_LABELS[ex.pattern] })),
    };
  });

  const restDays = plan.days.filter((d) => d.isRest).length;

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow={`v${plan.version}`}
        title={plan.name}
        description={`${plan.splitKind.replace(/_/g, ' ')} · ${days.length} training day(s), ${restDays} rest day(s) · generated by ${plan.generatorVersion}`}
      />

      <Card>
        <CardHeader
          title="Why this plan"
          action={<Info className="h-5 w-5 text-[var(--accent-2)]" aria-hidden="true" />}
        />
        <div className="px-5 pb-5">
          <BulletList items={plan.explanation} />
        </div>
      </Card>

      {equipment.profileId ? null : (
        <Notice tone="warn" title="No equipment profile is active">
          GymOS is planning bodyweight-only sessions. Set up your equipment to unlock the rest of
          the library. <Link className="underline" href="/equipment">Open Equipment</Link>
        </Notice>
      )}

      <PlanEditor days={days} addable={addableByDay} />

      <Card>
        <CardHeader
          title="Safety constraints applied"
          action={<TriangleAlert className="h-5 w-5 text-warn-500" aria-hidden="true" />}
        />
        <div className="px-5 pb-5 space-y-3">
          <BulletList
            items={[
              `Every exercise here is checked against your active equipment profile (${equipment.profileName ?? 'none'}).`,
              profile.limitations.length > 0
                ? `Movements that load ${profile.limitations.join(', ')} are excluded.`
                : 'No movement limitations are recorded on your profile.',
              profile.ageBand === 'adult_18_plus'
                ? 'Adult programming rules.'
                : 'Age-appropriate programming: conservative volume and no intensity targets.',
              'Swapping an exercise re-checks equipment before the swap is allowed.',
            ]}
          />
          <Notice tone="neutral">
            Exercise instructions in GymOS are an internal draft awaiting professional review. They
            are general information, not coaching. Stop anything that causes pain.
          </Notice>
        </div>
      </Card>
    </div>
  );
}
